func InternalServiceAccountClass(object Object) (ServiceAccountKind, error) {
	values, state := object.Attribute("objectClass")
	if state != AttributePresent {
		return 0, errors.Join(ErrNotServiceAccount, ErrAttributeUnavailable)
	}
	var kind ServiceAccountKind
	for _, value := range values {
		name, err := NewRawValue(value).Text()
		if err != nil {
			return 0, err
		}
		switch strings.ToLower(name) {
		case "msds-managedserviceaccount":
			if kind != 0 {
				return 0, ErrNotServiceAccount
			}
			kind = ServiceAccountStandalone
		case "msds-groupmanagedserviceaccount":
			if kind != 0 {
				return 0, ErrNotServiceAccount
			}
			kind = ServiceAccountGroupManaged
		case "msds-delegatedmanagedserviceaccount":
			return 0, ErrNotServiceAccount
		}
	}
	if kind == 0 {
		return 0, ErrNotServiceAccount
	}
	return kind, nil
}

func InternalServiceAccountClassName(kind ServiceAccountKind) string {
	if kind == ServiceAccountStandalone {
		return "msDS-ManagedServiceAccount"
	}
	if kind == ServiceAccountGroupManaged {
		return "msDS-GroupManagedServiceAccount"
	}
	return ""
}

func InternalServiceAccountClassFilter() Filter {
	return FilterAnd(
		FilterOr(
			FilterEqual("objectClass", FilterText("msDS-ManagedServiceAccount")),
			FilterEqual("objectClass", FilterText("msDS-GroupManagedServiceAccount")),
		),
		FilterNot(FilterEqual("objectClass", FilterText("msDS-DelegatedManagedServiceAccount"))),
	)
}

func InternalServiceAccountSecret(name string) bool {
	base, _, _ := strings.Cut(strings.ToLower(name), ";")
	switch base {
	case "*",
		"+",
		"unicodepwd",
		"userpassword",
		"dbcspwd",
		"ntpwdhistory",
		"lmpwdhistory",
		"supplementalcredentials",
		"msds-managedpassword",
		"msds-managedpasswordid",
		"msds-managedpasswordpreviousid",
		"mskds-rootkeydata",
		"msds-managedaccountprecededbylink",
		"msds-managedaccountsucceededbylink":
		return true
	}
	return false
}

func InternalValidateServiceAccountProjection(properties []string) error {
	for _, name := range properties {
		if InternalServiceAccountSecret(name) ||
			(len(name) > 0 && name[0] >= '0' && name[0] <= '9') {
			return ErrInvalidProperty
		}
	}
	return nil
}

