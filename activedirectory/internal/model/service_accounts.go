func InternalDecodeServiceAccount(object Object) (ServiceAccount, error) {
	account := ServiceAccount{
		DistinguishedName:     object.DistinguishedName,
		Raw:                   object,
		ServicePrincipalNames: object.Values("servicePrincipalName"),
	}
	kind, err := InternalServiceAccountClass(object)
	if err != nil {
		return account, err
	}
	account.Kind = kind
	d := InternalRootDSEDecoder{InternalAttributes: object.Attributes}
	account.Name = d.InternalText("name")
	account.SAMAccountName = d.InternalText("sAMAccountName")
	account.DNSHostName = d.InternalText("dNSHostName")
	account.DisplayName = d.InternalText("displayName")
	account.Description = d.InternalText("description")
	account.HomePage = d.InternalText("wWWHomePage")
	account.AccountExpires = InternalDecodeScalar(&d, "accountExpires", ParseFileTime)
	account.Certificates = object.Values("userCertificate")
	account.ManagedPasswordIntervalDays = InternalDecodeScalar(
		&d,
		"msDS-ManagedPasswordInterval",
		InternalParseUint32,
	)
	account.SupportedEncryptionTypes = InternalDecodeScalar(
		&d,
		"msDS-SupportedEncryptionTypes",
		func(s string) (Flags32, error) { return NewRawValue([]byte(s)).Flags32() },
	)
	if account.SupportedEncryptionTypes != nil {
		value := account.SupportedEncryptionTypes.Has(0x40)
		account.CompoundIdentitySupported = &value
	}
	for _, name := range []string{"objectGUID", "objectSid", "msDS-GroupMSAMembership"} {
		values := object.Values(name)
		if values.State == AttributeAbsent || values.State == AttributeUnloaded {
			continue
		}
		value, e := values.Single()
		if e == nil {
			switch name {
			case "objectGUID":
				v, x := value.GUID()
				e = x
				if e == nil {
					account.GUID = &v
				}
			case "objectSid":
				v, x := value.SID()
				e = x
				if e == nil {
					account.SID = &v
				}
			default:
				account.PasswordReaderDescriptorReturned = true
				account.PasswordReaders, e = InternalServiceAccountDescriptorReaders(value.Bytes())
			}
		}
		d.InternalErrors = append(d.InternalErrors, e)
	}
	account.AccountControl, err = InternalDecodeAccountControl(object, DirectoryADDS)
	return account, errors.Join(err, errors.Join(d.InternalErrors...))
}

func InternalServiceAccountMutationResult(
	m ObjectMutationResult,
	err error,
) (ServiceAccountMutationResult, error) {
	r := ServiceAccountMutationResult{Mutation: m}
	if m.After != nil {
		account, e := InternalDecodeServiceAccount(*m.After)
		r.Account = &account
		err = errors.Join(err, e)
	}
	return r, err
}

func InternalServiceAccountComputerProperties(p ServiceAccountProperties) ComputerProperties {
	return ComputerProperties{
		SAMAccountName:            p.SAMAccountName,
		DNSHostName:               p.DNSHostName,
		DisplayName:               p.DisplayName,
		Description:               p.Description,
		HomePage:                  p.HomePage,
		AccountExpires:            p.AccountExpires,
		CompoundIdentitySupported: p.CompoundIdentitySupported,
		KerberosEncryptionTypes:   p.KerberosEncryptionTypes,
	}
}

func InternalServiceAccountChanges(
	p ServiceAccountProperties,
	raw []AttributeChange,
) ([]AttributeChange, error) {
	for _, change := range raw {
		if InternalServiceAccountManaged(change.Attribute) {
			return nil, ErrInvalidServiceAccount
		}
	}
	changes, err := InternalComputerAttributeChanges(
		InternalServiceAccountComputerProperties(p),
		raw,
	)
	if err != nil {
		return nil, err
	}
	if p.ServicePrincipalNames != nil {
		change := AttributeChange{Attribute: "servicePrincipalName", Kind: AttributeClear}
		if len(*p.ServicePrincipalNames) > 0 {
			change.Kind = AttributeSet
		}
		for _, v := range *p.ServicePrincipalNames {
			if v == "" || !InternalValidDirectoryText(v) {
				return nil, ErrInvalidServiceAccount
			}
			change.Values = append(change.Values, NewRawValue([]byte(v)))
		}
		changes = append(changes, change)
	}
	return changes, nil
}

func InternalServiceAccountManaged(name string) bool {
	key := strings.ToLower(name)
	return InternalServiceAccountSecret(key) || InternalComputerManagedAttribute(key) ||
		key == "msds-groupmsamembership" ||
		key == "msds-managedpasswordinterval" ||
		key == "msds-hostserviceaccount" ||
		key == "msds-hostserviceaccountbl"
}

func InternalValidateServiceAccountControl(p AccountControlPatch) error {
	if p.ChangePasswordAtLogon != nil || p.PasswordNotRequired != nil ||
		p.PasswordNeverExpires != nil {
		return ErrAccountControlUnsupported
	}
	return InternalValidateAccountControlPatch(p)
}
