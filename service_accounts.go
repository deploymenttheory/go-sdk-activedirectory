var (
	ErrInvalidServiceAccount            = errors.New("invalid managed service account request")
	ErrNotServiceAccount                = errors.New("object is not an sMSA or gMSA")
	ErrServiceAccountPrerequisite       = errors.New("managed service account prerequisite is unavailable or not satisfied")
	ErrServiceAccountCreationIncomplete = errors.New("service account creation did not complete all stages; reconcile before further writes")
)

type ServiceAccountKind uint8

const (
	ServiceAccountStandalone ServiceAccountKind = iota + 1
	ServiceAccountGroupManaged
)

// ServiceAccountProperties changes only non-nil fields. An empty SPN slice
// clears that property. Password interval is creation-only. No password blob or
// password material is projected by these APIs, including via Properties.
type ServiceAccountProperties struct {
	SAMAccountName, DNSHostName, DisplayName, Description *string
	HomePage                                              *string
	AccountExpires                                        *FileTime
	CompoundIdentitySupported                             *bool
	KerberosEncryptionTypes                               *Flags32
	ServicePrincipalNames                                 *[]string
}

type ServiceAccount struct {
	Kind                                                        ServiceAccountKind
	DistinguishedName                                           string
	Name, SAMAccountName, DNSHostName, DisplayName, Description *string
	HomePage                                                    *string
	AccountExpires                                              *FileTime
	CompoundIdentitySupported                                   *bool
	Certificates                                                AttributeValues
	GUID                                                        *GUID
	SID                                                         *SID
	ManagedPasswordIntervalDays                                 *uint32
	SupportedEncryptionTypes                                    *Flags32
	ServicePrincipalNames                                       AttributeValues
	AccountControl                                              AccountControlState
	// PasswordReaders describes explicit ordinary allow ACEs granting Read
	// Property. Other ACEs are preserved; this is not an effective-access check.
	PasswordReaders                  []SID
	PasswordReaderDescriptorReturned bool
	Raw                              Object
}

type ServiceAccountResult struct {
	Account     *ServiceAccount
	Observation IdentityResult
}
type ServiceAccountsResult struct {
	Accounts    []ServiceAccount
	Observation SearchResult
}
type ServiceAccountMutationResult struct {
	Account  *ServiceAccount
	Mutation ObjectMutationResult
}

type CreateServiceAccountRequest struct {
	Kind ServiceAccountKind
	// Selects the reference's outbound-only gMSA creation form: no DNS host
	// name or inbound authentication configuration is supplied. This is not a
	// persistent server flag and does not constrain future directory changes.
	OutboundAuthenticationOnly bool
	Parent                     Identity
	Name                       string
	Properties                 ServiceAccountProperties
	Control                    AccountControlPatch
	// Standalone accounts receive a cryptographically random password when
	// omitted. Group-managed passwords are exclusively generated by the DC.
	InitialPassword             []byte `json:"-"`
	ManagedPasswordIntervalDays *uint32
	PasswordReaders             []Identity
	Attributes                  map[string][]RawValue
	Options                     ObjectMutationOptions
}

