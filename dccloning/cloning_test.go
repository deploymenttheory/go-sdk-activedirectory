func loadEvidence(t *testing.T, name string, value any) {
	t.Helper()
	data, err := os.ReadFile(filepath.Join("..", "docs", "research", "dc-cloning-evidence", name))
	if err != nil {
		t.Fatal(err)
	}
	if err := json.Unmarshal(bytes.TrimPrefix(data, []byte{0xef, 0xbb, 0xbf}), value); err != nil {
		t.Fatal(err)
	}
}

func equalFold(a, b string) (bool, error) { return strings.EqualFold(a, b), nil }

func TestCapturedServiceInventory(t *testing.T) {
	var capture struct {
		Observation struct {
			Files      []struct{ Path, Text string } `json:"files"`
			Services   []struct{ Name string }       `json:"services"`
			Exclusions []struct {
				Properties []struct{ Name, Value string }
			} `json:"exclusions"`
		} `json:"observation"`
	}
	loadEvidence(t, "server2025-readonly.json", &capture)
	var allowed []Entry
	for _, file := range capture.Observation.Files {
		if strings.Contains(strings.ToLower(file.Path), "defaultdccloneallowlist") {
			var err error
			allowed, err = ParseDefaultAllowList([]byte(file.Text))
			if err != nil {
				t.Fatal(err)
			}
		}
	}
	if len(allowed) != 156 {
		t.Fatalf("default entries: %d", len(allowed))
	}
	var installed, expected []Entry
	for _, s := range capture.Observation.Services {
		installed = append(installed, Entry{Name: s.Name, Type: Service})
	}
	for _, item := range capture.Observation.Exclusions {
		var entry Entry
		for _, p := range item.Properties {
			if p.Name == "Name" {
				entry.Name = p.Value
			}
			if p.Name == "Type" {
				entry.Type = Kind(p.Value)
			}
		}
		expected = append(expected, entry)
	}
	got, err := exclude(installed, allowed, equalFold)
	if err != nil || !reflect.DeepEqual(got, expected) {
		t.Fatalf("service reference mismatch: %v\ngot %#v\nwant %#v", err, got, expected)
	}
}

func TestCapturedCustomCasesAndGeneratedBytes(t *testing.T) {
	var capture struct {
		Observation struct {
			WithPrograms []Entry `json:"with_programs"`
			Cases        []struct {
				Name, XML, Encoding string
				Entries             []Entry
				Error               json.RawMessage
			} `json:"cases"`
			Generation []struct {
				Name  string
				Bytes string `json:"bytes_base64"`
			} `json:"generation"`
		} `json:"observation"`
	}
	loadEvidence(t, "server2025-contract-cases.json", &capture)
	for _, c := range capture.Observation.Cases {
		t.Run(c.Name, func(t *testing.T) {
			data := []byte(c.XML)
			if c.Encoding == "UTF-16LE-BOM" {
				words := utf16.Encode([]rune(c.XML))
				data = make([]byte, 2+len(words)*2)
				data[0] = 0xff
				data[1] = 0xfe
				for i, w := range words {
					binary.LittleEndian.PutUint16(data[2+i*2:], w)
				}
			}
			entries, err := ParseCustomAllowList(data)
			// These two files are silently ignored by PowerShell. The SDK's
			// intentional, documented structural validation returns a typed error.
			invalid := string(c.Error) != "null" || c.Name == "wrong-root" || c.Name == "wrong-namespace"
			if invalid {
				if !errors.Is(err, ErrInvalidList) {
					t.Fatalf("expected typed list error, got %v", err)
				}
				return
			}
			if err != nil {
				t.Fatal(err)
			}
			got, err := exclude(capture.Observation.WithPrograms, entries, equalFold)
			if err != nil || !reflect.DeepEqual(got, c.Entries) {
				t.Fatalf("reference mismatch: %v\ngot %#v\nwant %#v", err, got, c.Entries)
			}
		})
	}
	for _, c := range capture.Observation.Generation {
		if c.Name != "same-rank-existing-with-force" {
			continue
		}
		want, err := base64.StdEncoding.DecodeString(c.Bytes)
		if err != nil {
			t.Fatal(err)
		}
		got, err := EncodeCustomAllowList(capture.Observation.WithPrograms)
		if err != nil {
			t.Fatal(err)
		}
		if !bytes.Equal(got, want) {
			t.Fatalf("generated bytes differ\ngot %q\nwant %q", got, want)
		}
	}
}

func TestXMLEscapingAndValidation(t *testing.T) {
	input := []Entry{{Name: "& < > \" ' Cymru £ 😀", Type: Program}, {Name: "duplicate", Type: Service}, {Name: "duplicate", Type: Service}}
	xml, err := EncodeCustomAllowList(input)
	if err != nil {
		t.Fatal(err)
	}
	got, err := ParseCustomAllowList(xml)
	if err != nil || !reflect.DeepEqual(got, input) {
		t.Fatalf("roundtrip %v %#v", err, got)
	}
	for _, bad := range []string{"\x00", "\x01", "\xff", "\ufffe"} {
		if _, err := EncodeCustomAllowList([]Entry{{Name: bad, Type: Service}}); !errors.Is(err, ErrInvalidList) {
			t.Fatalf("encoded invalid text %q: %v", bad, err)
		}
	}
	if _, err := EncodeCustomAllowList(nil); !errors.Is(err, ErrInvalidList) {
		t.Fatal(err)
	}
	if _, err := ParseCustomAllowList([]byte{0xff, 0xfe, 1}); !errors.Is(err, ErrInvalidList) {
		t.Fatal(err)
	}
}

type fakeMachine struct {
	paths          locations
	entries        []Entry
	inventoryError error
	roleValue      Role
}

func (m fakeMachine) role(context.Context) (Role, error)           { return m.roleValue, nil }
func (m fakeMachine) locations(context.Context) (locations, error) { return m.paths, nil }
func (m fakeMachine) inventory(context.Context) ([]Entry, error)   { return m.entries, m.inventoryError }
func (m fakeMachine) equal(a, b string) (bool, error)              { return equalFold(a, b) }

const defaultFixture = `<DefaultCloneConfig><AllowList><Allow><Name>Included</Name><Type>Service</Type></Allow></AllowList><sysprepInformation><imaging/></sysprepInformation></DefaultCloneConfig>`

func fixtureMachine(t *testing.T) fakeMachine {
	t.Helper()
	dir := t.TempDir()
	defaultPath := filepath.Join(dir, "default.xml")
	if err := os.WriteFile(defaultPath, []byte(defaultFixture), 0600); err != nil {
		t.Fatal(err)
	}
	return fakeMachine{paths: locations{defaultPath: defaultPath, directories: []string{dir}}, entries: []Entry{{Name: "Included", Type: Service}, {Name: "Excluded", Type: Service}}, roleValue: Role{MachineRole: 5}}
}

func TestInspectionPartialAndFirstCustomFailure(t *testing.T) {
	m := fixtureMachine(t)
	cause := errors.New("denied inventory source")
	m.inventoryError = cause
	r, _, err := inspect(context.Background(), m, readList, true)
	if r.Complete || !r.AuthorizationLimited || len(r.Entries) != 1 || !errors.Is(err, cause) || !errors.Is(err, ErrIncomplete) {
		t.Fatalf("partial result %#v %v", r, err)
	}
	m.inventoryError = nil
	if err := os.WriteFile(filepath.Join(m.paths.directories[0], CustomFileName), []byte("<broken>"), 0600); err != nil {
		t.Fatal(err)
	}
	m.paths.directories = append(m.paths.directories, t.TempDir())
	valid, _ := EncodeCustomAllowList([]Entry{{Name: "Excluded", Type: Service}})
	os.WriteFile(filepath.Join(m.paths.directories[1], CustomFileName), valid, 0600)
	_, _, err = inspect(context.Background(), m, readList, true)
	if !errors.Is(err, ErrInvalidList) {
		t.Fatalf("fell through malformed higher-priority file: %v", err)
	}
}

func TestGenerationDefaultOnlyPreservationAndPublicationFailure(t *testing.T) {
	m := fixtureMachine(t)
	ctx := context.Background()
	dir := m.paths.directories[0]
	path := filepath.Join(dir, CustomFileName)
	seed, _ := EncodeCustomAllowList([]Entry{{Name: "Excluded", Type: Service}})
	os.WriteFile(path, seed, 0600)
	sentinel := filepath.Join(dir, "unrelated")
	os.WriteFile(sentinel, []byte("preserve"), 0600)
	called := 0
	publish := func(temp, dest string, overwrite bool) error {
		called++
		if !overwrite {
			t.Fatal("overwrite flag lost")
		}
		return os.Rename(temp, dest)
	}
	r, err := generate(ctx, m, GenerateOptions{Directory: dir}, readList, publish)
	if !errors.Is(err, ErrOutputExists) || r.Outcome != NotWritten || called != 0 {
		t.Fatalf("no-overwrite %#v %v", r, err)
	}
	r, err = generate(ctx, m, GenerateOptions{Directory: dir, Overwrite: true}, readList, publish)
	if err != nil || r.Outcome != Written || len(r.Result.Entries) != 1 || called != 1 {
		t.Fatalf("generate %#v %v", r, err)
	}
	got, _ := os.ReadFile(path)
	entries, err := ParseCustomAllowList(got)
	if err != nil || len(entries) != 1 || entries[0].Name != "Excluded" {
		t.Fatalf("generation subtracted custom: %#v %v", entries, err)
	}
	before := append([]byte(nil), got...)
	failure := errors.New("uncertain publication")
	r, err = generate(ctx, m, GenerateOptions{Directory: dir, Overwrite: true}, readList, func(string, string, bool) error { called++; return failure })
	if !errors.Is(err, failure) || r.Outcome != WriteUncertain || called != 2 {
		t.Fatalf("uncertain %#v %v", r, err)
	}
	got, _ = os.ReadFile(path)
	if !bytes.Equal(got, before) {
		t.Fatal("existing output changed before publication")
	}
	got, _ = os.ReadFile(sentinel)
	if string(got) != "preserve" {
		t.Fatal("unrelated file changed")
	}
	temps, _ := filepath.Glob(filepath.Join(dir, ".ad-sdk-cloning-*"))
	if len(temps) != 0 {
		t.Fatalf("temporary files leaked: %v", temps)
	}
}

func TestEmptyGenerationCancellationAndPrecedence(t *testing.T) {
	m := fixtureMachine(t)
	m.entries = m.entries[:1]
	never := func(string, string, bool) error { t.Fatal("unexpected publication"); return nil }
	r, err := generate(context.Background(), m, GenerateOptions{Directory: m.paths.directories[0]}, readList, never)
	if err != nil || r.Outcome != NotWritten {
		t.Fatalf("empty %#v %v", r, err)
	}
	ctx, cancel := context.WithCancel(context.Background())
	cancel()
	_, _, err = inspect(ctx, m, readList, true)
	if !errors.Is(err, context.Canceled) {
		t.Fatal(err)
	}
	m.entries = append(m.entries, Entry{Name: "excluded", Type: Service})
	lower := t.TempDir()
	m.paths.directories = append(m.paths.directories, lower)
	seed, _ := EncodeCustomAllowList([]Entry{{Name: "excluded", Type: Service}})
	os.WriteFile(filepath.Join(m.paths.directories[0], CustomFileName), seed, 0600)
	_, err = generate(context.Background(), m, GenerateOptions{Directory: lower, Overwrite: true}, readList, never)
	if !errors.Is(err, ErrPrecedence) {
		t.Fatalf("precedence: %v", err)
	}
}
